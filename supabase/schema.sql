-- Hamza Fragrance: secure database foundation for Supabase
-- Run this in Supabase SQL Editor after creating a project.
create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null default 'Hamza Fragrance',
  category text not null check (category in ('Men','Women','Unisex')),
  price_pkr integer not null check (price_pkr >= 0),
  compare_at_price_pkr integer check (compare_at_price_pkr is null or compare_at_price_pkr >= price_pkr),
  tag text,
  fragrance_notes text not null default '',
  description text not null default '',
  image_url text not null default '',
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text unique not null,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  delivery_address text not null,
  delivery_city text not null,
  customer_note text,
  subtotal_pkr integer not null check (subtotal_pkr >= 0),
  delivery_pkr integer not null check (delivery_pkr >= 0),
  total_pkr integer not null check (total_pkr = subtotal_pkr + delivery_pkr),
  status text not null default 'pending' check (status in ('pending','confirmed','processing','shipped','delivered','cancelled')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','pending','paid','refunded')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price_pkr integer not null check (unit_price_pkr >= 0),
  quantity integer not null check (quantity > 0),
  line_total_pkr integer not null check (line_total_pkr = unit_price_pkr * quantity)
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists products_active_idx on public.products(is_active);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Anyone can view active products" on public.products;
create policy "Anyone can view active products" on public.products
  for select to anon, authenticated using (is_active = true);

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins read orders" on public.orders;
create policy "Admins read orders" on public.orders
  for select to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders
  for update to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins read order items" on public.order_items;
create policy "Admins read order items" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  ));

create or replace function public.create_store_order(
  p_customer_name text,
  p_customer_phone text,
  p_customer_email text,
  p_delivery_address text,
  p_delivery_city text,
  p_customer_note text,
  p_items jsonb
) returns table(order_number text, total_pkr integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid;
  v_order_number text := 'HF-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
  v_subtotal integer := 0;
  v_delivery integer;
  v_total integer;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if length(trim(coalesce(p_customer_name,''))) < 2
     or length(trim(coalesce(p_customer_phone,''))) < 7
     or length(trim(coalesce(p_delivery_address,''))) < 5
     or length(trim(coalesce(p_delivery_city,''))) < 2 then
    raise exception 'Please provide valid customer and delivery details.';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your shopping bag is empty.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item ->> 'quantity')::integer;
    if v_qty < 1 or v_qty > 20 then raise exception 'Invalid product quantity.'; end if;
    select * into v_product from public.products
      where id = (v_item ->> 'product_id')::bigint and is_active = true
      for update;
    if not found then raise exception 'A selected product is no longer available.'; end if;
    if v_product.stock_quantity < v_qty then
      raise exception 'Insufficient stock for %.', v_product.name;
    end if;
    v_subtotal := v_subtotal + (v_product.price_pkr * v_qty);
  end loop;

  v_delivery := case when v_subtotal >= 5000 then 0 else 250 end;
  v_total := v_subtotal + v_delivery;

  insert into public.orders(
    order_number, customer_name, customer_phone, customer_email,
    delivery_address, delivery_city, customer_note,
    subtotal_pkr, delivery_pkr, total_pkr
  ) values (
    v_order_number, trim(p_customer_name), trim(p_customer_phone),
    nullif(trim(coalesce(p_customer_email,'')), ''),
    trim(p_delivery_address), trim(p_delivery_city),
    nullif(trim(coalesce(p_customer_note,'')), ''),
    v_subtotal, v_delivery, v_total
  ) returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item ->> 'quantity')::integer;
    select * into v_product from public.products
      where id = (v_item ->> 'product_id')::bigint and is_active = true
      for update;
    insert into public.order_items(order_id, product_id, product_name, unit_price_pkr, quantity, line_total_pkr)
    values (v_order_id, v_product.id, v_product.name, v_product.price_pkr, v_qty, v_product.price_pkr * v_qty);
    update public.products set stock_quantity = stock_quantity - v_qty, updated_at = now()
      where id = v_product.id;
  end loop;

  return query select v_order_number, v_total;
end;
$$;

revoke all on function public.create_store_order(text,text,text,text,text,text,jsonb) from public;
grant execute on function public.create_store_order(text,text,text,text,text,text,jsonb) to anon, authenticated;

